rep.h2("1. Ручной расчет линейной регрессии")
rep.p("Коэффициенты прямой y = a_{0} + a_{1}·x находятся методом наименьших квадратов:")
rep.formula("a_{1} = (n·Σxy − Σx·Σy) / (n·Σx^{2} − (Σx)^{2}),   a_{0} = (Σy − a_{1}·Σx) / n.")
rep.formula("r = (n·Σxy − Σx·Σy) / √((n·Σx^{2} − (Σx)^{2})·(n·Σy^{2} − (Σy)^{2})),   R^{2} = r^{2}.")
