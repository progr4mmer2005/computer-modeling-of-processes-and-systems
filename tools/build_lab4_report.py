def eq(text):
    """Уравнение модели из программы -> запись с запятой и степенями."""
    import re
    text = text.replace("·", "·")
    text = re.sub(r"(\d)\.(\d)", r"\1,\2", text)
    text = re.sub(r"x\^([0-9,]+)", r"x^{\1}", text)
    text = re.sub(r"e\^\(([^)]*)\)", r"e^{\1}", text)
    text = re.sub(r"(\d,?\d*)e([+-])0?(\d+)", lambda m: f"{m.group(1)}·10^{{{'−' if m.group(2) == '-' else ''}{m.group(3)}}}", text)
    return text.replace("-", "−")


