sx, sy, sxy, sx2, sy2 = v["sum_x"], v["sum_y"], v["sum_xy"], v["sum_x2"], v["sum_y2"]
top, bottom, bottom_y = n * sxy - sx * sy, n * sx2 - sx ** 2, n * sy2 - sy ** 2
ybar = y.mean()
yhat1 = v["a0"] + v["a1"] * x[0]
sse = ((y - (v["a0"] + v["a1"] * x)) ** 2).sum()
sst = ((y - ybar) ** 2).sum()

rep.h2("1. Ручной расчет линейной регрессии")
rep.p("Ищем прямую y = a_{0} + a_{1}·x: a_{1} – наклон (на сколько в среднем меняется y при росте x на 1), "
      "a_{0} – сдвиг (значение y при x = 0). Коэффициенты находятся методом наименьших квадратов (МНК): прямая "
      "выбирается так, чтобы сумма квадратов отклонений точек от нее была наименьшей. Из этого условия "
      "получаются формулы")
rep.formula("a_{1} = (n·Σxy − Σx·Σy) / (n·Σx^{2} − (Σx)^{2}),   a_{0} = (Σy − a_{1}·Σx) / n,")
rep.p("где n – число наблюдений; Σx и Σy – суммы всех x и всех y; Σxy – сумма произведений x·y по всем "
      "наблюдениям; Σx^{2} – сумма квадратов x. "
      f"По таблице 1: n = {n}, Σx = {num(sx, 4)}, Σy = {num(sy, 2)}, Σxy = {num(sxy, 5)}, Σx^{{2}} = {num(sx2, 8)}, "
      f"Σy^{{2}} = {num(sy2, 4)}. Подставляем:")
rep.formula(f"a_{{1}} = ({n}·{num(sxy, 5)} − {num(sx, 4)}·{num(sy, 2)}) / ({n}·{num(sx2, 8)} − {num(sx, 4)}^{{2}}) = "
            f"{num(top, 5)} / {num(bottom, 7)} = {num(v['a1'], 2)};", numbered=False)
rep.formula(f"a_{{0}} = ({num(sy, 2)} − ({num(v['a1'], 2)})·{num(sx, 4)}) / {n} = {num(v['a0'])}.", numbered=False)
rep.p(f"Уравнение регрессии: y = {num(v['a0'])} {num(v['a1'], 2)}·x. Знак a_{{1}} отрицательный: с ростом меди в "
      f"воде содержание меди в волосах в среднем слегка убывает, но при таком малом |r| это не закономерность, а "
      f"случайный разброс. Большое по модулю значение a_{{1}} объясняется единицами измерения: x – тысячные доли "
      f"мг/л, поэтому при росте x на 0,001 y меняется всего на {num(abs(v['a1']) * 0.001, 2)} мкг/г.")
rep.p("Тесноту и направление линейной связи показывает коэффициент корреляции r (от −1 до +1):")
rep.formula("r = (n·Σxy − Σx·Σy) / √((n·Σx^{2} − (Σx)^{2})·(n·Σy^{2} − (Σy)^{2})).")
rep.formula(f"r = {num(top, 5)} / √({num(bottom, 7)}·({n}·{num(sy2, 4)} − {num(sy, 2)}^{{2}})) = "
            f"{num(top, 5)} / √({num(bottom, 7)}·{num(bottom_y, 2)}) = {num(v['r'])}.", numbered=False)
rep.p("Коэффициент детерминации R^{2} показывает, какую долю разброса y объясняет модель. Он сравнивает "
      "промахи модели с промахами самого простого способа угадать y – назвать для всех наблюдений среднее ȳ:")
rep.formula("R^{2} = 1 − Σ(y − ŷ)^{2} / Σ(y − ȳ)^{2},")
rep.p("где y – измеренное значение из таблицы 1; ŷ – значение, которое дает формула модели, если подставить в "
      "нее x этого наблюдения; ȳ = Σy / n – среднее всех y. Числитель – сумма квадратов промахов модели, "
      "знаменатель – сумма квадратов отклонений от среднего. Если модель попадает во все точки, числитель равен "
      "нулю и R^{2} = 1; если модель не лучше среднего, R^{2} = 0.")
rep.p(f"Расчет для прямой. Среднее ȳ = {num(sy, 2)} / {n} = {num(ybar)}. Для первого наблюдения (x = {num(x[0], 4)}, "
      f"y = {num(y[0], 2)}): ŷ = {num(v['a0'])} {num(v['a1'], 2)}·{num(x[0], 4)} = {num(yhat1, 3)}; "
      f"(y − ŷ)^{{2}} = ({num(y[0], 2)} − {num(yhat1, 3)})^{{2}} = {num((y[0] - yhat1) ** 2, 3)}; "
      f"(y − ȳ)^{{2}} = ({num(y[0], 2)} − {num(ybar)})^{{2}} = {num((y[0] - ybar) ** 2, 3)}. Так же для всех {n} "
      f"наблюдений, затем суммы: Σ(y − ŷ)^{{2}} = {num(sse, 2)}, Σ(y − ȳ)^{{2}} = {num(sst, 2)}.")
rep.formula(f"R^{{2}} = 1 − {num(sse, 2)} / {num(sst, 2)} = {num(1 - sse / sst)}.", numbered=False)
rep.p(f"Для прямой R^{{2}} совпадает с квадратом коэффициента корреляции: r^{{2}} = ({num(v['r'])})^{{2}} = "
      f"{num(v['r'] ** 2)}. Прямая объясняет только {num(v['r'] ** 2 * 100, 1)} % разброса.")

rep.h2("2. Три модели и статистические характеристики")
