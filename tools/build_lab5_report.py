rep.h1("Решение")
rep.p("Все расчеты выполнены программой lab5.py (Приложение А). Ее вывод показан на рисунках 3 и 4.")

rep.h2("1. Ручной расчет линейной регрессии")
rep.p("Коэффициенты прямой y = a_{0} + a_{1}·x находятся методом наименьших квадратов:")
rep.formula("a_{1} = (n·Σxy − Σx·Σy) / (n·Σx^{2} − (Σx)^{2}),   a_{0} = (Σy − a_{1}·Σx) / n.")
rep.formula("r = (n·Σxy − Σx·Σy) / √((n·Σx^{2} − (Σx)^{2})·(n·Σy^{2} − (Σy)^{2})),   R^{2} = r^{2}.")
rep.p(f"Суммы по таблице 1: Σx = {num(v['sum_x'], 4)}, Σy = {num(v['sum_y'], 2)}, Σxy = {num(v['sum_xy'], 5)}, "
      f"Σx^{{2}} = {num(v['sum_x2'], 7)}, Σy^{{2}} = {num(v['sum_y2'], 4)}. Подстановка при n = {n} дает "
      f"a_{{1}} = {num(v['a1'], 2)}, a_{{0}} = {num(v['a0'])}, то есть y = {num(v['a0'])} {num(v['a1'], 2)}·x. "
      f"Коэффициент корреляции r = {num(v['r'])}, R^{{2}} = {num(v['r'] ** 2)}. Знак a_{{1}} отрицательный: "
      f"с ростом меди в воде содержание меди в волосах в среднем слегка убывает, но при таком малом |r| "
      f"это не закономерность, а случайный разброс.")

rep.h2("2. Три модели и статистические характеристики")
