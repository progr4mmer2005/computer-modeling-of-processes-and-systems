def eq(text):
    text = re.sub(r"(\d)\.(\d)", r"\1,\2", text)
    text = re.sub(r"x\^(-?[\d,]+)", r"x^{\1}", text)
    return text.replace("-", "−").replace("x²", "x^{2}")


