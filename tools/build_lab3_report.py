def vec(values):
    return "(" + "; ".join(num(float(v), 0) if float(v).is_integer() else num(float(v), 2)
                           for v in values) + ")"


def span(s):
    return f"[{num(s[0], 0)}; {num(s[1], 0)}]"


def eig_text(task):
    parts = []
    for re_, im in task["eigenvalues"]:
        if abs(im) < 1e-12:
            parts.append(num(re_, 4))
        elif im > 0:
            parts.append(f"{num(re_, 4)} ± {num(im, 4)}i")
    return ", ".join(parts)


def fig_width(file):
    key = file.split("_", 2)[-1].rsplit(".", 1)[0]
    return FIG_WIDTH.get(key, 14)


def stats_of(task, variant, solver):
    return next(s for s in task["stats"] if s["variant"] == variant and s["solver"] == solver)


def figures(task, keys):
    numbers = {}
    for f in task["figures"]:
        key = f["file"].split("_", 2)[-1].rsplit(".", 1)[0]
        if key in keys:
            numbers[key] = rep.figure(RES / f["file"], f["caption"].replace(" — ", ": "),
                                      fig_width(f["file"]))
    return numbers


def compare_table(task, caption):
    rows = [[num(r["t"], 2), COORD[r["coord"]], num(r["ode23"], 6), num(r["ode113"], 6),
             num(r["exact"], 6), sci(r["diff"]) if r["diff"] else "0"] for r in task["compare"]]
    return rep.table(["t", "Координата", "ode23", "ode113", "Точное решение", "|ode23 − ode113|"],
                     rows, caption, widths=[1.6, 2.2, 2.9, 2.9, 2.9, 3.0])


def stats_table(task, caption):
    rows = [[VARIANT[s["variant"]], s["solver"], sci(s["rtol"], 0), s["steps"], s["nfev"],
             sci(s["h_min"]), sci(s["h_max"]), sci(max(s["max_err"]))] for s in task["stats"]]
    return rep.table(["Вариант расчета", "Решатель", "RelTol", "Шагов", "Вызовов f",
                      "h min", "h max", "Макс. погрешность"], rows, caption,
                     widths=[3.4, 1.7, 1.5, 1.3, 1.6, 2.1, 2.1, 2.6],
                     align=["left"] + ["center"] * 7)


def final_table(task, caption):
    rows = [[VARIANT[r["variant"]], r["span"].replace(".", ","), COORD[r["coord"]],
             num(float(r["ode23"]), 6), num(float(r["ode113"]), 6), num(float(r["exact"]), 6)]
            for r in task["final"]]
    return rep.table(["Вариант", "Интервал", "Координата", "ode23", "ode113", "Точное"],
                     rows, caption, widths=[4.2, 1.9, 2.2, 2.6, 2.6, 2.6],
                     align=["left"] + ["center"] * 5)


def plan_table(task, caption):
    rows = [["базовый", span(task["span"]), vec(task["x0"])],
            ["другой интервал", span(task["alt_span"]), vec(task["x0"])],
            ["другие начальные условия", span(task["span"]), vec(task["alt_x0"])],
            ["строгая точность", span(task["span"]), vec(task["x0"])]]
    return rep.table(["Вариант расчета", "Интервал интегрирования", "Начальные условия",
                      "RelTol / AbsTol"],
                     [r + [("10⁻⁸ / 10⁻¹⁰" if r[0] == "строгая точность" else "10⁻³ / 10⁻⁶")]
                      for r in rows], caption, widths=[4.6, 3.6, 4.2, 3.6],
                     align=["left", "center", "center", "center"])


def solver_summary(task):
    a, b = stats_of(task, "базовый", "ode23"), stats_of(task, "базовый", "ode113")
    sa, sb = stats_of(task, "строгая точность", "ode23"), stats_of(task, "строгая точность", "ode113")
    diff = max(r["diff"] for r in task["compare"])
    return (f"При точности по умолчанию ode23 сделал {a['steps']} шагов и {a['nfev']} вызовов правой "
            f"части, его наибольшая погрешность относительно точного решения {sci(max(a['max_err']))}. "
            f"Решатель ode113 сделал {b['steps']} шагов и {b['nfev']} вызовов, погрешность "
            f"{sci(max(b['max_err']))}. Наибольшее расхождение между решателями в контрольных точках "
            f"равно {sci(diff)}, то есть результаты совпадают в пределах заданной точности. "
            f"При RelTol = 10⁻⁸ погрешность уменьшилась до {sci(max(sa['max_err']))} (ode23, "
            f"{sa['steps']} шагов) и {sci(max(sb['max_err']))} (ode113, {sb['steps']} шагов).")


